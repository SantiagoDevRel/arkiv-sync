import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { assertCheckoutUnchanged, createOutputDirectory, snapshotCheckout, withIsolatedCheckout } from './isolated-checkout.mjs';

function fixture(callback) {
  const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'checkout-isolation-test-'));
  const checkout = path.join(temporary, 'source');
  fs.mkdirSync(checkout);
  for (const file of ['package.json', 'src/index.ts', 'dist/index.js', 'node_modules/example/index.js', '.git/HEAD']) {
    const target = path.join(checkout, file);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, file === 'package.json' ? '{"name":"isolation-fixture"}' : 'original bytes');
  }
  try { callback({ checkout, temporary }); }
  finally { fs.rmSync(temporary, { recursive: true }); }
}

test('isolated writes leave all checkout bytes, dependencies and Git files unchanged', () => fixture(({ checkout }) => {
  const before = snapshotCheckout(checkout);
  let owned;
  withIsolatedCheckout(({ root, temporary }) => {
    owned = temporary;
    assert.notEqual(root, checkout);
    assert(root.startsWith(os.tmpdir() + path.sep));
    assert(!fs.existsSync(path.join(root, 'node_modules')));
    assert(!fs.existsSync(path.join(root, '.git')));
    fs.writeFileSync(path.join(root, 'package.json'), '{"sdk":"changed only in copy"}');
    fs.writeFileSync(path.join(root, 'dist/index.js'), 'mutated generated bytes');
    fs.mkdirSync(path.join(root, 'node_modules'));
    fs.writeFileSync(path.join(root, 'node_modules/sdk.json'), '{}');
    fs.writeFileSync(path.join(temporary, 'report.json'), '{}');
  }, { checkout });
  assert(!fs.existsSync(owned));
  assertCheckoutUnchanged(checkout, before);
}));

test('the assertion rejects source, ignored output, dependency and Git mutations', () => fixture(({ checkout }) => {
  const before = snapshotCheckout(checkout);
  const cases = ['src/index.ts', 'dist/index.js', 'node_modules/example/index.js', '.git/HEAD'];
  for (const file of cases) {
    const target = path.join(checkout, file);
    const original = fs.readFileSync(target);
    fs.writeFileSync(target, 'mutated bytes');
    assert.throws(() => assertCheckoutUnchanged(checkout, before), /byte-identical/);
    fs.writeFileSync(target, original);
    assertCheckoutUnchanged(checkout, before);
  }
  const added = path.join(checkout, 'pack-dry-run.json');
  fs.writeFileSync(added, '{}');
  assert.throws(() => assertCheckoutUnchanged(checkout, before), /byte-identical/);
  fs.unlinkSync(added);
  assertCheckoutUnchanged(checkout, before);
  console.log(JSON.stringify({ status: 'PASS', checkoutMutationRed: cases.length + 1, restoredFixtureGreen: true }));
}));

test('callback failures still assert checkout identity and clean their own copy', () => fixture(({ checkout }) => {
  let owned;
  const before = snapshotCheckout(checkout);
  assert.throws(() => withIsolatedCheckout(({ root, temporary }) => {
    owned = temporary;
    fs.writeFileSync(path.join(root, 'package.json'), 'changed in failed copy');
    throw new Error('intentional tool failure');
  }, { checkout }), /intentional tool failure/);
  assert(!fs.existsSync(owned));
  assertCheckoutUnchanged(checkout, before);
  assert.throws(() => withIsolatedCheckout(() => {
    fs.writeFileSync(path.join(checkout, 'src/index.ts'), 'unexpected origin mutation');
    throw new Error('intentional tool failure');
  }, { checkout }), /byte-identical/);
}));

test('explicit output refuses checkout paths and all existing paths', () => fixture(({ checkout, temporary }) => {
  const before = snapshotCheckout(checkout);
  const existing = path.join(temporary, 'existing');
  fs.mkdirSync(existing);
  assert.throws(() => createOutputDirectory(checkout, existing), /EEXIST/);
  assert.throws(() => createOutputDirectory(checkout, checkout), /outside the checkout/);
  assert.throws(() => createOutputDirectory(checkout, path.join(checkout, 'evidence')), /outside the checkout/);
  const output = createOutputDirectory(checkout, path.join(temporary, 'external'));
  fs.writeFileSync(path.join(output, 'report.json'), '{}', { flag: 'wx' });
  assert.throws(() => createOutputDirectory(checkout, output), /EEXIST/);
  assertCheckoutUnchanged(checkout, before);
}));

test('included source symlinks cannot expose the original checkout to copied tools', () => fixture(({ checkout }) => {
  fs.symlinkSync('index.ts', path.join(checkout, 'src/alias.ts'));
  const before = snapshotCheckout(checkout);
  let called = false;
  assert.throws(() => withIsolatedCheckout(() => { called = true; }, { checkout }), /must not link back/);
  assert.equal(called, false);
  assertCheckoutUnchanged(checkout, before);
}));
